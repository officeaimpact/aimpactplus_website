/**
 * Собирает абсолютный URL без `new URL(...)`, чтобы сохранить кириллицу
 * в `site.domain` (IDN). Принимает относительный путь (`/about`),
 * абсолютный URL (`https://...`) или пустое значение.
 *
 * @example absoluteUrl("/about") → "https://ии-туризм.рф/about"
 */
export function absoluteUrl(path?: string): string {
  if (!path) return site.domain;
  if (/^https?:\/\//i.test(path)) return path;
  const normalized = path.startsWith("/") ? path : `/${path}`;
  return `${site.domain}${normalized}`;
}

